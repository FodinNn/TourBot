package handlers

import (
	"log"
	"strings"
)

var commands = map[string]string{
	"/start": "Привет! Я бот-путеводитель по Казани.\n\n" +
		"Я умею:\n" +
		"/help — список команд\n" +
		"/kremlin — о Казанском кремле\n" +
		"/bauman — улица Баумана\n" +
		"/food — где поесть",

	"/help": "Вот что я умею:\n" +
		"/start — приветствие\n" +
		"/kremlin — Казанский кремль\n" +
		"/bauman — улица Баумана\n" +
		"/food — татарская кухня",

	"/kremlin": "Казанский кремль — главная достопримечательность города. " +
		"Объект Всемирного наследия ЮНЕСКО. Внутри: мечеть Кул-Шариф, " +
		"башня Сююмбике, Благовещенский собор.",

	"/bauman": "Улица Баумана — пешеходная улица в центре Казани. " +
		"Здесь много кафе, магазинов и уличных музыкантов. " +
		"Начинается от Кремля и идёт до площади Тукая.",

	"/food": "Татарская кухня: попробуй эчпочмак, чак-чак, " +
		"кыстыбый и бешбармак. Много мест на Баумана и в Кремле.",
}

func Handle(text string) string {
	cmd := strings.ToLower(strings.TrimSpace(text))

	if !strings.HasPrefix(cmd, "/") {
		return "Я понимаю только команды. Напиши /help, чтобы увидеть список."
	}

	reply, ok := commands[cmd]
	if !ok {
		log.Printf("Неизвестная команда: %s", cmd)
		return "Не знаю такой команды. Напиши /help, чтобы увидеть список."
	}

	return reply
}
