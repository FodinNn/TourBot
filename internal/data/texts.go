func SeasonAdvice() string {
	switch time.Now().Month() {
	case time.December, time.January, time.February:
		return "❄️ Сезонный совет: зимой в Казани работают катки и новогодние ярмарки — загляните на Баумана и к Кремлю!"
	case time.March, time.April, time.May:
		return "🌷 Сезонный совет: весной набережные особенно хороши — берите тёплую куртку и отправляйтесь гулять."
	case time.June, time.July, time.August:
		return "☀️ Сезонный совет: летом отличная идея — прогулка на теплоходе по Волге и Казанке."
	default:
		return "🍂 Сезонный совет: осенью Казань особенно фотогенична — золотые парки и мягкий свет на закате."
	}
}
