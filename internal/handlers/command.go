func Handle(text string) string {
	cmd := strings.ToLower(strings.TrimSpace(text))

	if cmd == "" {
		return "Напишите /start, чтобы открыть меню."
	}

	reply, ok := commands[cmd]
	if !ok {
		log.Printf("Неизвестный запрос: %s", cmd)
		return "Не знаю такого. Напишите /start или /help, чтобы увидеть меню."
	}

	return reply
}
